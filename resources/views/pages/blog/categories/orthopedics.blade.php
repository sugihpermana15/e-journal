<h4 class="blog-details__title-2">Motion is Lotion: Why Strength Training Can Help Osteoarthritis</h4>
<p class="blog-details__text-1">Many people with knee or hip osteoarthritis avoid the gym because movement hurts.
    Modern guidance increasingly emphasizes the opposite: appropriate strength training can reduce pain, improve
    function, and make everyday movement easier.</p>
<p class="blog-details__text-2">The goal isn’t extreme impact—it’s progressive loading with good form, enough recovery,
    and a plan that respects flare-ups.</p>

<h4 class="blog-details__title-3">Practical principles</h4>
<ul class="blog-details__points-list list-unstyled">
    <li><div class="icon"></div><p>Start with tolerable ranges and low-to-moderate loads; build gradually.</p></li>
    <li><div class="icon"></div><p>Prioritize consistency over intensity; track symptoms and adjust volume.</p></li>
    <li><div class="icon"></div><p>Use strengthening to improve joint support and confidence in movement.</p></li>
</ul>

